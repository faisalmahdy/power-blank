export function fireInterval(w: WeaponDef): number {
  return 60 / w.rpm;
}

export function magOf(w: WeaponDef): number {
  return w.kits.includes("ext") ? w.magExt : w.mag;
}

export function recoilOf(w: WeaponDef, shotI: number): [number, number] {
  const i = Math.min(Math.max(0, shotI), w.recoil.length - 1);
  return w.recoil[i]!;
}

export function spreadOf(
  w: WeaponDef,
  moving: boolean,
  ads: boolean,
  crouch = false,
  airborne = false,
): number {
  if (w.pellets > 1) {
    let s = ads ? w.adsSpread : moving ? w.moveSpread : w.spread;
    if (crouch) s *= 0.78;
    if (airborne) s *= 1.35;
    return s;
  }
  let s: number;
  if (ads) s = w.kits.includes("rd") ? w.adsSpread * 0.5 : w.adsSpread;
  else if (moving) s = w.kits.includes("lsr") ? w.moveSpread * 0.62 : w.moveSpread;
  else s = w.kits.includes("lsr") ? w.spread * 0.62 : w.spread;
  if (crouch) s *= 0.68;
  if (airborne) s += 0.032;
  return s;
}
