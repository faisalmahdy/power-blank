import type { KitId, WeaponDef, WeaponId } from "./types";

const r = (pitch: number, yaw: number): [number, number] => [pitch, yaw];

/** Full-mag pattern: unique climb, then hold the tail. Never loop back to shot 1. */
function magPattern(core: Array<[number, number]>, len: number): Array<[number, number]> {
  const out = core.slice();
  const tail = core.slice(Math.max(0, core.length - 4));
  let i = 0;
  while (out.length < len) {
    const t = tail[i % Math.max(1, tail.length)] ?? r(0.008, 0);
    out.push([t[0], t[1]]);
    i++;
  }
  return out;
}

